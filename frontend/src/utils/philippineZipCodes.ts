function normalizeKey(str: string): string {
  if (!str) return '';
  return str
    .toUpperCase()
    .replace(/^CITY OF\s+/i, '')
    .replace(/^MUNICIPALITY OF\s+/i, '')
    .replace(/\s+CITY$/i, '')
    .trim();
}

/**
 * Looks up Philippine ZIP/Postal Code given City/Municipality and optional Province.
 */
export function getPhilippineZipCode(cityMunicipality?: string, province?: string): string {
  if (!cityMunicipality && !province) return '';

  const rawCity = (cityMunicipality || '').toUpperCase().trim();
  const cleanCity = normalizeKey(cityMunicipality || '');
  const rawProv = (province || '').toUpperCase().trim();
  const cleanProv = normalizeKey(province || '');

  // 1. Check composite province|city exact matches first
  if (rawProv && rawCity && PHILIPPINE_ZIP_CODES[`${rawProv}|${rawCity}`]) {
    return PHILIPPINE_ZIP_CODES[`${rawProv}|${rawCity}`];
  }
  if (cleanProv && cleanCity && PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity}`]) {
    return PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity}`];
  }

  // 2. Direct exact match by raw city (e.g. "PIDIGAN", "LUCENA CITY")
  if (rawCity && PHILIPPINE_ZIP_CODES[rawCity]) {
    return PHILIPPINE_ZIP_CODES[rawCity];
  }

  // 3. Direct match by normalized city (e.g. "PIDIGAN", "LUCENA")
  if (cleanCity && PHILIPPINE_ZIP_CODES[cleanCity]) {
    return PHILIPPINE_ZIP_CODES[cleanCity];
  }

  // 4. Fallback to province default
  if (rawProv && PROVINCE_DEFAULT_ZIP[rawProv]) {
    return PROVINCE_DEFAULT_ZIP[rawProv];
  }
  if (cleanProv && PROVINCE_DEFAULT_ZIP[cleanProv]) {
    return PROVINCE_DEFAULT_ZIP[cleanProv];
  }

  // 5. Substring match across city keys
  for (const [key, val] of Object.entries(PHILIPPINE_ZIP_CODES)) {
    const cityPart = key.includes('|') ? key.split('|')[1] : key;
    if (cleanCity && (cleanCity.includes(cityPart) || cityPart.includes(cleanCity))) {
      return val;
    }
  }

  return '4301';
}
